/**
 * Generates the artifact-local .htaccess template merging static prerendering,
 * secure asset delivery, TLS enforcement, and API-before-SPA routing for HostPapa shared cPanel.
 */
export function generateHtaccess(existingAuthBlock = "", origin = "https://www.gazaairport.com") {
  if (!["https://www.gazaairport.com", "https://staging.gazaairport.com"].includes(origin)) throw new Error("Invalid HTTPS redirect origin");
  const authHeader = existingAuthBlock
    ? `${existingAuthBlock}\n`
    : `# Optional Apache Directory Privacy Auth block preserved for staging\n`;

  return `# ----------------------------------------------------------------------
# HostPapa cPanel Apache Configuration for Gaza Airport / Palestinian Airlines
# Artifact-local merged rules: Static Pre-rendering + Private Laravel API Bridge
# Generated by tools/hostpapa-release
# ----------------------------------------------------------------------

${origin === "https://staging.gazaairport.com" ? '<IfModule mod_headers.c>\nHeader always set X-Robots-Tag "noindex, nofollow, noarchive"\n</IfModule>\n' : ""}
${authHeader}# Security: Prevent directory listing
Options -Indexes

# Default directory indexes
DirectoryIndex index.html index.php

<IfModule mod_rewrite.c>
RewriteEngine On
RewriteBase /

# ----------------------------------------------------------------------
# 1. Require actual TLS (reject plain HTTP without trusting spoofed headers)
# ----------------------------------------------------------------------
RewriteCond %{HTTPS} !=on
RewriteCond %{SERVER_PORT} !=443
RewriteRule ^ ${origin}%{REQUEST_URI} [L,R=301]

# ----------------------------------------------------------------------
# 2. Block access to sensitive dotfiles, backend sources, and system files
# ----------------------------------------------------------------------
<FilesMatch "(^\\.|\\.(?:env.*|git.*|log|sql|md|yml|yaml|json|lock|sh|phar|bak|swp)$)">
    Require all denied
</FilesMatch>

# Keep inherited cPanel Directory Privacy in force for every public file.

# Block any accidental direct requests into private directories in webroot
RewriteRule ^(?:storage|vendor|app|bootstrap|config|database|tests|resources|docs|bin)/ - [F,L,NC]

# ----------------------------------------------------------------------
# 3. API Routes: MUST PRECEDE static routing and SPA fallbacks
# ----------------------------------------------------------------------
# Forward /api and /api/v1 requests directly to public index.php bridge
RewriteCond %{REQUEST_URI} ^/api(?:/.*)?$ [NC]
RewriteRule ^ index.php [L,QSA]

# ----------------------------------------------------------------------
# 4. Existing regular files: serve directly
# ----------------------------------------------------------------------
RewriteCond %{REQUEST_FILENAME} -f
RewriteRule ^ - [L]

# ----------------------------------------------------------------------
# 5. Prerendered directory index matching: /path or /path/ -> /path/index.html
# ----------------------------------------------------------------------
# Only rewrite if an index.html actually exists in that directory.
# This ensures directories without index.html (e.g. /admin, /ar/admin)
# fall through to the SPA shell rules below.
RewriteCond %{DOCUMENT_ROOT}/$1/index.html -f [OR]
RewriteCond %{REQUEST_FILENAME}/index.html -f
RewriteRule ^(.*)/?$ $1/index.html [L]

# ----------------------------------------------------------------------
# 6. Missing static assets: return 404 directly (never serve HTML shell or PHP)
# ----------------------------------------------------------------------
RewriteCond %{REQUEST_URI} \\.(?:css|js|mjs|png|jpe?g|gif|webp|avif|svg|ico|woff2?|ttf|eot|mp4|webm|map)$ [NC]
RewriteRule ^ - [R=404,L]

# ----------------------------------------------------------------------
# 7. Dynamic SPA fallbacks:
# ----------------------------------------------------------------------
# 7a. Arabic Admin fallback (matches /ar/admin, /ar/admin/, /ar/admin/*)
RewriteRule ^ar/admin(?:/.*)?$ ar/admin/_shell.html [L]

# 7b. English Admin fallback (matches /admin, /admin/, /admin/*)
RewriteRule ^admin(?:/.*)?$ admin/_shell.html [L]

# 7c. Arabic Public dynamic fallback (/ar/manage/*, /ar/account/*, Arabic 404s, etc.)
RewriteRule ^ar(?:/.*)?$ ar/_shell.html [L]

# 7d. English Public dynamic fallback (/manage/*, /account/*, English 404s, etc.)
RewriteRule ^ _shell.html [L]
</IfModule>
`;
}
