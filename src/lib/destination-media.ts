function attachSources(
  meta: (typeof DESTINATION_PHOTO_METADATA)[DestinationPhotoId],
  sources: string[],
): DestinationPhoto {
  return {
    ...meta,
    variants: meta.variants.map((v, i) => ({
      ...v,
      src: sources[i] ?? "",
    })),
  };
}

